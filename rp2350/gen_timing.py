"""Write rp2350/core/timing.h from test/timing.py, so the C harness and the Python tests share one
source for every delay, period and input offset (Spec 1: no other file may hardcode them).

    python3 rp2350/gen_timing.py          # rerun after any change to test/timing.py
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "test"))
import timing as T  # noqa: E402


def offs(name, t):
    return f"#define TT_N_{name} {len(t)}\n#define TT_{name} {{{', '.join(str(x) for x in t)}}}"


body = f"""// GENERATED by rp2350/gen_timing.py from test/timing.py. Do not edit: change test/timing.py and rerun.
// Clock convention (docs/host_timing.md): in host clock k the host drives input word k and samples
// uo_out just before the rising edge that captures word k. D counts from a unit's first input word
// to its first result byte; the second and third bytes follow on the next two clocks.
#ifndef TT_TIMING_H
#define TT_TIMING_H

// block latencies
#define TT_L_CAP {T.L_CAP}
#define TT_L_MUL {T.L_MUL}
#define TT_L_PACK {T.L_PACK}

// clocks per unit (the input period the host must keep)
#define TT_P_F {T.P_F}
#define TT_P_I {T.P_I}
#define TT_P_B {T.P_B}
#define TT_P_S {T.P_S}

// input offsets of each coefficient within its unit
{offs("OFFS_F", T.OFFS_F)}
{offs("OFFS_I", T.OFFS_I)}
{offs("OFFS_B", T.OFFS_B)}
{offs("OFFS_S", T.OFFS_S)}

// output delays at the pins
#define TT_D_F {T.D_F}
#define TT_D_I {T.D_I}
#define TT_D_B {T.D_B}
#define TT_D_S {T.D_S}

#endif
"""
out = os.path.join(HERE, "core", "timing.h")
os.makedirs(os.path.dirname(out), exist_ok=True)
with open(out, "w") as fh:
    fh.write(body)
print(f"wrote {out}: D = {T.D_F}/{T.D_I}/{T.D_B}/{T.D_S}, P = {T.P_F}/{T.P_I}/{T.P_B}/{T.P_S}")
