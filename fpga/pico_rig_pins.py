"""The Pico 2 W <-> Tang Nano 20K wiring, in one place. Writes fpga/tangnano20k_pico.cst and prints the
wiring table used in docs/PICO_TANG_RIG.md, so the constraints and the documentation cannot drift apart.
The Pico side must match rp2350/rp/tt_rp.h (TT_TARGET=pico2w_tang).

    python3 fpga/pico_rig_pins.py            # rewrite the .cst, print the Markdown table

Tang Nano 20K header pins and FPGA pin numbers: Sipeed's pin label image
(wiki.sipeed.com, tang_nano_20k_pinlabel.png). Headers are seen from the top with the USB-C connector
at the top; left header L1-L20 and right header R1-R20 count from the top. Pico 2 W physical pins: the
standard Pico pinout (pin 1 = GP0, top left with the USB connector at the top).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))

# Pico 2 W GPIO -> physical header pin
PICO_PIN = {0: 1, 1: 2, 2: 4, 3: 5, 4: 6, 5: 7, 6: 9, 7: 10, 8: 11, 9: 12, 10: 14, 11: 15, 12: 16, 13: 17,
            14: 19, 15: 20, 16: 21, 17: 22, 18: 24, 19: 25, 20: 26, 21: 27, 22: 29, 26: 31, 27: 32, 28: 34}

# (chip signal, Pico GPIO, Tang header position, FPGA pin, direction seen from the FPGA, note)
WIRES = [
    ("ui_in[0]", 0, "L1", 73, "in", ""),
    ("ui_in[1]", 1, "L2", 74, "in", ""),
    ("ui_in[2]", 2, "L3", 75, "in", ""),
    ("ui_in[3]", 3, "L4", 85, "in", "SDIO_D1 (leave the TF slot empty)"),
    ("ui_in[4]", 4, "L8", 27, "in", ""),
    ("ui_in[5]", 5, "L9", 28, "in", ""),
    ("ui_in[6]", 6, "L10", 25, "in", ""),
    ("ui_in[7]", 7, "L11", 26, "in", ""),
    ("uio[0]", 8, "L12", 29, "in", "coefficient bit 8"),
    ("uio[1]", 9, "L13", 30, "in", "coefficient bit 9"),
    ("uio[2]", 10, "L14", 31, "in", "coefficient bit 10"),
    ("uio[3]", 11, "R3", 76, "in", "coefficient bit 11"),
    ("uio[4]", 12, "R4", 80, "in", "valid; SDIO_D2"),
    ("uio[5]", 26, "R5", 42, "in", "sof"),
    ("uio[6]", 27, "R6", 41, "in", "op bit 0"),
    ("uio[7]", 28, "R7", 56, "in", "op bit 1; I2S_BCLK of the unused amplifier"),
    ("uo_out[0]", 13, "R8", 54, "out", "I2S_DIN of the unused amplifier"),
    ("uo_out[1]", 14, "R10", 48, "out", ""),
    ("uo_out[2]", 15, "R11", 55, "out", "I2S_LRCK of the unused amplifier"),
    ("uo_out[3]", 16, "R12", 49, "out", ""),
    ("uo_out[4]", 17, "R13", 86, "out", ""),
    ("uo_out[5]", 18, "R17", 72, "out", ""),
    ("uo_out[6]", 19, "R18", 71, "out", ""),
    ("uo_out[7]", 20, "R19", 53, "out", "EDID_CLK (no HDMI cable)"),
    ("clk", 21, "L5", 77, "in", "GCLKT_1: global clock input"),
    ("rst_n", 22, "R20", 52, "in", "EDID_DAT (no HDMI cable)"),
]
GROUNDS = [(3, "L20"), (18, "R15"), (28, "R2")]     # Pico physical GND pin, Tang GND position

PORT = {"clk": "tt_clk", "rst_n": "tt_rst_n"}


def port(sig):
    if sig in PORT:
        return PORT[sig]
    name, idx = sig.rstrip("]").split("[")
    return {"ui_in": "tt_ui", "uio": "tt_uio", "uo_out": "tt_uo"}[name] + f"[{idx}]"


def check():
    fpga = [w[3] for w in WIRES]
    gpio = [w[1] for w in WIRES]
    assert len(set(fpga)) == len(fpga) and len(set(gpio)) == len(gpio) == 26
    assert set(gpio) == set(PICO_PIN), "every usable Pico 2 W GPIO is used exactly once"
    assert not set(fpga) & {15, 16, 17, 18, 19, 20, 51, 79}, "LEDs, amplifier enable and WS2812 stay free"
    # the firmware's PIO windows (tt_rp.h): uo_out on GPIO 13-20 in order, clk 21, rst_n 22,
    # ui_in + uio[0..4] on GPIO 0-12 in order, uio[5..7] on GPIO 26-28
    order = {w[0]: w[1] for w in WIRES}
    assert [order[f"uo_out[{i}]"] for i in range(8)] == list(range(13, 21))
    assert [order[f"ui_in[{i}]"] for i in range(8)] + [order[f"uio[{i}]"] for i in range(5)] == list(range(13))
    assert [order[f"uio[{i}]"] for i in (5, 6, 7)] == [26, 27, 28] and order["clk"] == 21 and order["rst_n"] == 22


def write_cst():
    lines = ["// GENERATED by fpga/pico_rig_pins.py: Tang Nano 20K pins for the Pico 2 W rig (docs/PICO_TANG_RIG.md).",
             "// Inputs are pulled down, so an unwired or unpowered Pico leaves the design idle and in reset.", "",
             'IO_LOC "clk" 4;', 'IO_PORT "clk" IO_TYPE=LVCMOS33 PULL_MODE=UP;', ""]
    for sig, gp, pos, pin, d, note in WIRES:
        lines.append(f'IO_LOC "{port(sig)}" {pin};')
        attrs = "PULL_MODE=DOWN" if d == "in" else "DRIVE=8"
        lines.append(f'IO_PORT "{port(sig)}" IO_TYPE=LVCMOS33 {attrs};   // {sig}, Pico GP{gp}, header {pos}')
    lines.append("")
    for i, pin in enumerate((15, 16, 17, 18, 19, 20)):
        lines += [f'IO_LOC "led[{i}]" {pin};', f'IO_PORT "led[{i}]" IO_TYPE=LVCMOS33 PULL_MODE=UP DRIVE=8;']
    with open(os.path.join(HERE, "tangnano20k_pico.cst"), "w") as fh:
        fh.write("\n".join(lines) + "\n")


def table():
    out = ["| Chip signal | Pico 2 W | Pico pin | → / ← | Tang Nano header | FPGA pin | Note |",
           "|---|---|---|---|---|---|---|"]
    for sig, gp, pos, pin, d, note in sorted(WIRES, key=lambda w: PICO_PIN[w[1]]):
        arrow = "→" if d == "in" else "←"
        out.append(f"| `{sig}` | GP{gp} | {PICO_PIN[gp]} | {arrow} | {pos} | {pin} | {note} |")
    for pp, pos in GROUNDS:
        out.append(f"| GND | GND | {pp} | – | {pos} | GND | |")
    return "\n".join(out)


if __name__ == "__main__":
    check()
    write_cst()
    print(table())
