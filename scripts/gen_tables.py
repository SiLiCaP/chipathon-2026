"""Generate src/zeta_rom.v and the ROM / gamma tables in tables/.

    ROM[k]   = 17^BitRev7(k) mod 3329          k = 0..127
    gamma_i  = 17^(2*BitRev7(i)+1) mod 3329    i = 0..127
    ROM'[k]  = ROM[k] * 2197^-1 mod 3329       (2197^-1 = 944)
    gamma'_i = gamma_i * 2197^-1 mod 3329

The multiplier returns 2197 * a * b (three K-RED rounds), so the chip stores the scaled
ROM'. Basemul derives gamma'_i as ROM'[64 + (i >> 1)], negated (3329 - x) for
odd i; this script checks that identity for all 128.

The tables come from the reference model, test/ntt_ref.py.

Run from the repo root:  python3 scripts/gen_tables.py
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "test"))
from ntt_ref import GAMMA, GAMMA_S, KM_INV, Q, ZETA, ZETA_S  # noqa: E402  (single source)

assert KM_INV == 944
for i in range(128):
    z = ZETA_S[64 + (i >> 1)]
    assert GAMMA_S[i] == (Q - z if i & 1 else z), i
assert 0 not in ZETA_S

ROM_V = """\
/*
 * SPDX-License-Identifier: Apache-2.0
 *
 * zeta_rom: scaled zetas ROM'[k] = 17^BitRev7(k) * 2197^-1 mod 3329, k = 0..127.
 * The multiplier returns 2197 * a * b (K-RED), so b * ROM'[k] comes out as
 * b * zeta. Combinational lookup. GENERATED by scripts/gen_tables.py, do not edit.
 */

`default_nettype none

module zeta_rom (
    input  wire [6:0]  addr,
    output reg  [11:0] data
);

  always @(*) begin
    case (addr)
{cases}
      default: data = 12'd0;
    endcase
  end

endmodule
"""


def main():
    cases = "\n".join(f"      7'd{k:<3}: data = 12'd{z};" for k, z in enumerate(ZETA_S))
    with open(os.path.join(ROOT, "src", "zeta_rom.v"), "w") as fh:
        fh.write(ROM_V.replace("{cases}", cases))

    os.makedirs(os.path.join(ROOT, "tables"), exist_ok=True)
    for name, values in (("zeta", ZETA), ("gamma", GAMMA),
                         ("zeta_scaled", ZETA_S), ("gamma_scaled", GAMMA_S)):
        with open(os.path.join(ROOT, "tables", f"{name}.hex"), "w") as fh:
            fh.writelines(f"{v:03x}\n" for v in values)
        with open(os.path.join(ROOT, "tables", f"{name}.txt"), "w") as fh:
            fh.writelines(f"{i} {v}\n" for i, v in enumerate(values))
    print("wrote src/zeta_rom.v and tables/{zeta,gamma,zeta_scaled,gamma_scaled}.{hex,txt}")


if __name__ == "__main__":
    main()
